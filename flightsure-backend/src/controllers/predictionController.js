import Flight from '../models/Flight.js';
import Prediction from '../models/Prediction.js';
import { generateGroqPrediction } from '../services/groqPredictionService.js';
import { AppError } from '../utils/errors.js';
import { sendSuccess } from '../utils/respond.js';

export async function predict(request, response) {
  const flight = await Flight.findById(request.body.flightId);
  if (!flight) throw new AppError(404, 'FLIGHT_NOT_FOUND', 'No stored flight matches this identifier.');
  const config = request.app.locals.config;
  const result = await generateGroqPrediction(flight, config);
  const saved = await Prediction.create({
    userId: request.user._id,
    flightId: flight._id,
    ...result,
    predictionTime: new Date(result.predictionTime)
  });
  return sendSuccess(response, 200, 'Uncalibrated informational estimate generated by Groq.', { prediction: saved });
}

export async function history(request, response) {
  const predictions = await Prediction.find({ userId: request.user._id })
    .sort({ predictionTime: -1 }).limit(100).populate('flightId');
  return sendSuccess(response, 200, 'Your prediction history.', { predictions });
}
